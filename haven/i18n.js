const originals = new WeakMap();

function textNodes(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent) continue;
    if (parent.closest("script, style, #lang-modal, #rules, [data-no-i18n]")) continue;
    if (!node.nodeValue || !node.nodeValue.trim()) continue;
    nodes.push(node);
  }
  return nodes;
}

export function applyLanguage(lang, { persist = true } = {}) {
  const es = lang === "es";
  const code = es ? "es" : "en";
  document.documentElement.lang = code;
  document.documentElement.dataset.language = code;

  for (const node of textNodes(document.body)) {
    if (!originals.has(node)) originals.set(node, node.nodeValue);
    const original = originals.get(node);
    const key = original.trim();
    const lead = original.match(/^\s*/)[0];
    const tail = original.match(/\s*$/)[0];
    const next = es && DICT[key] ? DICT[key] : key;
    node.nodeValue = lead + next + tail;
  }

  const copy = RULES[code];
  document.querySelectorAll("#rules [data-i18n]").forEach((el) => {
    const value = copy[el.getAttribute("data-i18n")];
    if (value != null) el.textContent = value;
  });

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    const on = btn.dataset.setLang === code;
    btn.classList.toggle("is-on", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });

  if (persist) {
    try {
      localStorage.setItem("haven-lang", code);
    } catch {
      /* private mode */
    }
  }
}
